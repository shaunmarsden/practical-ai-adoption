import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { readFile, mkdir } from 'node:fs/promises';
import { base, assertStaticRequests } from './browser-support.mjs';
import { emptyTestResults, testResultsJSON } from '../../../docs/workbench/test-results.mjs';

const folder = process.env.WORKBENCH_OUTPUT || 'test-results/workbench-observations';
await mkdir(folder, { recursive: true });
const browser = await chromium.launch({ headless: true, channel: 'chromium' });
try {
  for (const width of [1440, 320]) {
    const context = await browser.newContext({ viewport: { width, height: 850 }, acceptDownloads: true });
    const page = await context.newPage(), requests = [], errors = [];
    page.on('request', req => requests.push({ url: req.url(), method: req.method(), body: req.postData() }));
    page.on('pageerror', e => errors.push(e.message));
    await page.goto(base + '/workbench/');
    const status = page.locator('#result-C4-status'), actual = page.locator('#result-C4-actual');
    await status.selectOption('Observed - problem (reported)');
    await page.getByRole('button', { name: 'Save results JSON' }).click();
    assert.match(await page.locator('#test-results-status').innerText(), /Describe what actually happened/);
    await actual.fill('Fictional: unsafe date was accepted despite an unresolved mismatch.');
    await page.locator('#result-C4-evidence').fill('Fictional evidence Q4\n<script>bad()</script>');
    await page.locator('#result-C4-followup').fill('Stop and review the issue. Do not continue.');
    await page.locator('#result-C1-status').selectOption('Observed - acceptable (reported)');
    await page.locator('#result-C1-actual').fill('Fictional: ordinary sample was reviewed.');
    assert.match(await page.locator('#test-results-changes').innerText(), /edits are only in this page/);
    await page.getByRole('button', { name: 'Preview observations' }).click();
    const preview = await page.locator('#test-results-preview').innerText();
    assert.ok(preview.includes('unsafe date was accepted'));
    assert.ok(preview.includes('ordinary sample was reviewed'));
    assert.ok(preview.includes('Stop and review the issue'));
    assert.equal(await page.locator('#test-results-preview script').count(), 0);
    const textPromise = page.waitForEvent('download');
    await page.getByRole('button', { name: 'Export observations text' }).click();
    const textFile = await textPromise;
    assert.equal(textFile.suggestedFilename(), 'ai-adoption-test-observations.txt');
    const exported = await readFile(await textFile.path(), 'utf8');
    assert.ok(exported.includes('Fictional evidence Q4'));
    assert.ok(exported.includes('Reported status: Observed - problem (reported)'));
    const savePromise = page.waitForEvent('download');
    await page.getByRole('button', { name: 'Save results JSON' }).click();
    const jsonFile = await savePromise;
    assert.equal(jsonFile.suggestedFilename(), 'ai-adoption-test-results.json');
    const saved = await readFile(await jsonFile.path(), 'utf8');
    assert.equal(JSON.parse(saved).cases[3].actual, 'Fictional: unsafe date was accepted despite an unresolved mismatch.');
    await page.reload();
    assert.equal(await page.locator('#result-C4-status').inputValue(), 'Not run', 'no automatic retention');
    await page.locator('#result-C2-actual').fill('Do not overwrite me');
    const picker = page.locator('#reopen-test-results');
    page.once('dialog', d => d.dismiss());
    await picker.setInputFiles({ name: 'results.json', mimeType: 'application/json', buffer: Buffer.from(saved) });
    assert.equal(await page.locator('#result-C2-actual').inputValue(), 'Do not overwrite me', 'cancel replacement');
    page.once('dialog', d => d.accept());
    await picker.setInputFiles({ name: 'results.json', mimeType: 'application/json', buffer: Buffer.from(saved) });
    assert.equal(await page.locator('#result-C4-actual').inputValue(), 'Fictional: unsafe date was accepted despite an unresolved mismatch.');
    assert.equal(await page.locator('#result-C4-status').inputValue(), 'Observed - problem (reported)');
    assert.equal(await page.locator('#result-C1-status').inputValue(), 'Observed - acceptable (reported)');
    assert.match(await page.locator('#test-results-changes').innerText(), /No newer test-result edits/);
    await picker.setInputFiles({ name: 'bad.json', mimeType: 'application/json', buffer: Buffer.from('{bad') });
    assert.match(await page.locator('#test-results-status').innerText(), /Could not reopen results/);
    assert.equal(await page.locator('#result-C4-status').inputValue(), 'Observed - problem (reported)', 'bad file preserves outcomes');
    const badEntries = emptyTestResults();
    badEntries[0].status = 'Observed - acceptable (reported)'; badEntries[0].actual = 'Fictional good result';
    const badFormat = testResultsJSON(badEntries).replace('"version": 1', '"version": 2');
    await picker.setInputFiles({ name: 'unsupported.json', mimeType: 'application/json', buffer: Buffer.from(badFormat) });
    assert.match(await page.locator('#test-results-status').innerText(), /Could not reopen results/);
    assert.equal(await page.locator('#result-C4-status').inputValue(), 'Observed - problem (reported)');
    await page.locator('#result-C4-followup').fill('New follow-up not saved');
    assert.match(await page.locator('#test-results-changes').innerText(), /edits are only in this page/);
    page.once('dialog', d => d.dismiss());
    await page.getByRole('button', { name: 'Clear test observations' }).click();
    assert.equal(await page.locator('#result-C4-status').inputValue(), 'Observed - problem (reported)', 'clear cancelled');
    page.once('dialog', d => d.accept());
    await page.getByRole('button', { name: 'Clear test observations' }).click();
    assert.equal(await page.locator('#result-C4-status').inputValue(), 'Not run');
    assert.equal(await page.locator('#test-results-preview').isVisible(), false);
    const allowed = ['/', '/workbench/', '/workbench/style.css', '/workbench/app.mjs', '/workbench/content.mjs', '/workbench/example.mjs', '/workbench/test-sheet.mjs', '/workbench/test-results.mjs', '/workbench/test-results-ui.mjs', '/workbench/draft.mjs', '/workbench/changes.mjs', '/pilot-readiness/icon.svg'];
    assertStaticRequests(requests, allowed);
    assert.deepEqual(errors, []);
    assert.deepEqual(await page.evaluate(() => [localStorage.length, sessionStorage.length, document.cookie]), [0, 0, '']);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await context.close();
  }
  console.log('Reported test-result browser checks passed: desktop and mobile, actual export, JSON reopen, adversarial files, failure retention, cancel, clear and privacy.');
} finally { await browser.close(); }
