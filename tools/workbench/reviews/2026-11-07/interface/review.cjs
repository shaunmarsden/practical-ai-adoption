const {chromium}=require('playwright');
const fs=require('fs');
const path=require('path');
const out=__dirname;
(async()=>{
 const browser=await chromium.launch({headless:true});
 const page=await browser.newPage({viewport:{width:1280,height:900},acceptDownloads:true});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:8768/workbench/');
 await page.locator('#workbench').waitFor({state:'visible'});
 const results={url:page.url(),initialDefaults:await page.locator('select').evaluateAll(es=>es.map(e=>({id:e.id,value:e.value})))};
 for(let i=0;i<5;i++) await page.locator('#next-step').click();
 results.blankFinal={nextDisabled:await page.locator('#next-step').isDisabled(),heading:await page.locator('#panels section:not([hidden]) h2').innerText(),text:await page.locator('#panels section:not([hidden])').innerText()};
 await page.locator('#review').click();
 fs.writeFileSync(path.join(out,'blank-preview.txt'),await page.locator('#summary').innerText());
 let dl=page.waitForEvent('download');await page.locator('#export').click();await(await dl).saveAs(path.join(out,'blank-export.txt'));
 await page.locator('#steps button').nth(2).click();
 await page.locator('#permissions').fill('Fictional exercise only. Permission for operational use is unknown.');
 await page.locator('#steps button').nth(3).click();
 await page.locator('#evidenceType').selectOption('Fictional exercise');
 await page.locator('#issues').fill('Fictional case: two outputs invented dates. No operational permission is established. No actual V2 review or human decision has happened.');
 await page.locator('#steps button').nth(4).click();
 await page.locator('#readiness').selectOption('COMPLETE RECORD - HUMAN DECISION REQUIRED');
 results.v2={text:await page.locator('#panels section:not([hidden])').innerText(),link:await page.getByRole('link',{name:'Open Pilot Readiness Assessment V2 (new tab)',exact:true}).evaluate(e=>({href:e.getAttribute('href'),target:e.target,rel:e.rel}))};
 await page.locator('#steps button').nth(5).click();
 await page.locator('#decision').selectOption('Continue within an existing authorised boundary');
 await page.locator('#review').click();
 dl=page.waitForEvent('download');await page.locator('#export').click();await(await dl).saveAs(path.join(out,'contradictory-export.txt'));
 results.contradictory={authority:await page.locator('#decisionOwner').inputValue(),date:await page.locator('#decisionDate').inputValue(),status:await page.locator('#status').innerText(),summary:await page.locator('#summary').innerText()};
 await page.setViewportSize({width:320,height:740});
 await page.locator('#steps button').nth(4).click();
 await page.locator('#readiness').scrollIntoViewIfNeeded();
 await page.screenshot({path:path.join(out,'mobile-v2.png')});
 results.mobileV2=await page.locator('#readiness-selection').evaluate(e=>({text:e.textContent,rect:e.getBoundingClientRect().toJSON(),viewport:innerWidth,scrollWidth:document.documentElement.scrollWidth,clientWidth:document.documentElement.clientWidth}));
 await page.locator('#steps button').nth(5).click();
 await page.locator('#decision').scrollIntoViewIfNeeded();
 await page.screenshot({path:path.join(out,'mobile-decision.png')});
 results.mobileDecision=await page.locator('#decision-selection').evaluate(e=>({text:e.textContent,rect:e.getBoundingClientRect().toJSON(),viewport:innerWidth,scrollWidth:document.documentElement.scrollWidth}));
 results.errors=errors;
 fs.writeFileSync(path.join(out,'observations.json'),JSON.stringify(results,null,2));
 await browser.close();
 console.log(JSON.stringify({initialDefaults:results.initialDefaults,blankFinalNextDisabled:results.blankFinal.nextDisabled,mobileV2:results.mobileV2,mobileDecision:results.mobileDecision,errors}));
})().catch(e=>{console.error(e);process.exit(1)});
